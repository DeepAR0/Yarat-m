import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const { version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const config = JSON.parse(await readFile(resolve(root, 'release/config.json'), 'utf8'));
const html = await readFile(resolve(root, 'dist/client/index.html'), 'utf8');
assert.ok(html.includes('Gemblast Saga'));
assert.ok(!/https?:\/\/(fonts|ai\.google)/.test(html));
const project = await readFile(resolve(root, 'ios/App/App.xcodeproj/project.pbxproj'), 'utf8');
assert.equal((project.match(/PrivacyInfo\.xcprivacy in Resources \*\//g) ?? []).length, 2, 'Manifest must be registered exactly once in the resource phase.');
assert.ok(project.includes(`MARKETING_VERSION = ${version};`));
assert.equal((project.match(new RegExp(`CURRENT_PROJECT_VERSION = ${config.buildNumber};`, 'g')) ?? []).length, 2, 'Both native build configurations must match release buildNumber.');
assert.ok(project.includes('CODE_SIGN_ENTITLEMENTS = App/App.entitlements;'));
const privacy = await readFile(resolve(root, 'ios/App/App/PrivacyInfo.xcprivacy'), 'utf8');
assert.ok(privacy.includes('CA92.1') && privacy.includes('NSPrivacyAccessedAPICategoryUserDefaults'));
const nativeConfig = JSON.parse(await readFile(resolve(root, 'ios/App/App/capacitor.config.json'), 'utf8'));
assert.equal(nativeConfig.appName, 'Gemblast Saga');
assert.ok(!nativeConfig.server?.url, 'Release must use bundled assets.');
const info = await readFile(resolve(root, 'ios/App/App/Info.plist'), 'utf8');
assert.ok(info.includes(config.admob.iosAppId));
assert.ok(info.includes('SKAdNetworkItems') && info.includes('cstr6suwn9.skadnetwork'));
const spm = await readFile(resolve(root, 'ios/App/CapApp-SPM/Package.swift'), 'utf8');
assert.ok(spm.includes('CapacitorCommunityAdmob'), 'Native AdMob package must survive cap sync.');
const nativeSource = await readFile(resolve(root, 'ios/App/App/SceneDelegate.swift'), 'utf8');
assert.ok(nativeSource.includes('registerPluginInstance(GemblastGameCenterPlugin())'));
const entitlements = await readFile(resolve(root, 'ios/App/App/App.entitlements'), 'utf8');
assert.equal(entitlements.includes('com.apple.developer.game-center'), config.gameCenter.enabled);
for (const page of ['privacy.html', 'support.html']) {
  const built = await readFile(resolve(root, 'dist/client', page), 'utf8');
  const bundled = await readFile(resolve(root, 'ios/App/App/public', page), 'utf8');
  assert.ok(built.includes(version));
  assert.equal(bundled, built, 'Native policy/help assets must match current web build.');
}
const icon = await readFile(resolve(root, 'branding/app-icon-1024.png'));
assert.equal(icon.readUInt32BE(16), 1024); assert.equal(icon.readUInt32BE(20), 1024);
assert.equal(icon[25], 2, 'App icon must be RGB without alpha.');
const assets = await readdir(resolve(root, 'dist/client/assets'));
assert.ok(assets.some(file => file.endsWith('.js')));
console.log('Release source checks passed. Xcode archive, signing, native device tests and App Store metadata still require a Mac and the developer account.');
